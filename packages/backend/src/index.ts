export interface BackendDependencies { database: Database; clock?: Clock; credentials?: CredentialStore; notificationSecrets?: NotificationSecretStore; modelSecrets?: ModelSecretStore; modelEndpointValidator?: ModelEndpointValidator; modelProbeClient?: ModelProbeClient; webhookValidator?: WebhookAddressValidator; eventCredentials?: WritableEventCredentials; stepUpVerifier?: StepUpVerifier; proposalVerifier?: ProposalVerifier; customerDnsVerifier?: CustomerDnsVerifier; npmRegistry?: NpmRegistryPort; webAuthn?: { rpID: string; origin: string; rpName?: string; verifyPassword?: (userId: string, password: string) => Promise<boolean | null> }; actionVerifier?: ActionVerifier }
export function createBackend(deps: BackendDependencies) {
  const stepUp = deps.webAuthn ? createWebAuthnStepUpService({ ...deps, webAuthn: deps.webAuthn }) : null;
  const stepUpVerifier = stepUp?.verifier ?? deps.stepUpVerifier;
  return { corrections: createCorrectionService(deps), validations: createValidationService(deps), protection: createProtectionService({ ...deps, ...(deps.credentials ? { credentials: deps.credentials } : {}) }), executionArtifacts: createExecutionArtifactService(deps.database), workflowExceptions: createWorkflowExceptionService({ database:deps.database, ...(stepUpVerifier ? { stepUpVerifier } : {}) }), actions: createActionService({ ...deps, ...(stepUpVerifier ? { stepUpVerifier } : {}) }), operations: createOperationsService(deps), retention: createRetentionService(deps.database), decisionRecords: createDecisionRecordService(deps), notifications: createNotificationService(deps), investigationModels: createInvestigationModelService({ database: deps.database, ...(deps.modelSecrets ? { secrets: deps.modelSecrets } : {}), ...(deps.modelEndpointValidator ? { endpointValidator: deps.modelEndpointValidator } : {}), ...(deps.modelProbeClient ? { probeClient: deps.modelProbeClient } : {}) }), investigations: createInvestigationService(deps.database), runs: createRunService(deps), events: createEventService(deps), web: createWebService(deps), outbox: createOutboxService(deps), jobs: createJobService(deps), proposals: createProposalService({ ...deps, ...(stepUpVerifier ? { stepUpVerifier } : {}) }), executions: createExecutionService(deps), assessments: createAssessmentService(deps), customers: createCustomerService(deps), telemetry: createTelemetryService(deps), context: createContextService(deps), github: createGitHubConnectionService(deps), triage: createTriageService(deps), members: createMemberService(deps), stepUp };
}
export type Backend = ReturnType<typeof createBackend>;
